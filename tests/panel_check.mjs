import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

globalThis.HTMLElement = class {};
globalThis.window = {confirm: () => false};
globalThis.defaultConfig = () => ({device:'preview', theme:'ember', pages:[{id:'home', title:'Home', parent:'', lights:[]}], template:''});
globalThis.confirmDialog = () => {};
let Panel;
globalThis.customElements = {define: (_name, type) => { Panel = type; }};
vm.runInThisContext(fs.readFileSync('custom_components/ha_dial/www/panel.js', 'utf8').replace(/^import .*\n/gm, '').replace(/^if \(!customElements.get.*\n/m, ''));

const panel = new Panel();
const nodes = Object.fromEntries(['select','.error','.save','.reset','.state','ha-dial-panel-editor','ha-dial-card'].map(key => [key, {}]));
nodes['ha-dial-panel-editor'].setConfig = function(config) { this.config = config; };
nodes['ha-dial-card'].setConfig = function(config) { this.config = config; };
panel.querySelector = key => nodes[key];
panel.querySelectorAll = () => [];
panel.definitions = {first:{theme:'ember', pages:[{id:'one'}]}, second:{theme:'cobalt', pages:[{id:'two'}]}};
const calls = [];
panel._hass = {callWS: async message => { calls.push(message); return {deployment:'waiting'}; }};
panel.selectDevice('first', true);
assert.equal(panel.draft.pages[0].id, 'one');
assert.equal(nodes['ha-dial-card'].config.device, 'preview');
panel.draft = {...panel.draft, theme:'rose'}; panel.dirty = true;
panel.selectDevice('second');
assert.equal(panel.device, 'first', 'switching cannot discard a draft silently');
await panel.save();
assert.equal(calls[0].device, 'first');
assert.equal(calls[0].definition.theme, 'rose');
assert.equal(panel.dirty, false);
panel.selectDevice('second');
assert.equal(panel.draft.pages[0].id, 'two');
panel.selectDevice('new_dial');
assert.equal(panel.dirty, true, 'a new Dial can be saved without editing');

// Reset Dial is available whatever else has happened, including after a save and during a stuck one.
assert.ok(!nodes['.reset'].disabled);
await panel.save();
assert.ok(!nodes['.reset'].disabled, 'a finished save must not leave Reset disabled');
assert.equal(nodes['.save'].disabled, true);
assert.ok(!nodes.select.disabled);
let finishSave;
panel._hass.callWS = message => { calls.push(message); return message.type === 'ha_dial/configure' ? new Promise(resolve => { finishSave = resolve; }) : Promise.resolve({cleared:true}); };
panel.dirty = true;
const stuck = panel.save();
assert.ok(!nodes['.reset'].disabled, 'a save in progress must not disable Reset');
assert.equal(nodes['.save'].disabled, true);
assert.equal(nodes.select.disabled, true);
const reset = panel.reset('new_dial');
assert.equal(nodes['.reset'].disabled, true, 'only a reset in progress disables Reset');
await reset;
assert.equal(calls.at(-1).type, 'ha_dial/reset');
assert.ok(!nodes['.reset'].disabled);
assert.equal(nodes['.state'].textContent, 'Reset sent to Dial');
assert.equal(panel.definitions.new_dial, undefined);
finishSave({deployment:'waiting'});
await stuck;
assert.ok(!nodes['.reset'].disabled);
console.log('Panel device selection, draft isolation, saving and Reset availability passed');
